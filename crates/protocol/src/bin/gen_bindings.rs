//! Generate TypeScript bindings and JSON Schema from the protocol types.
//!
//! Usage: gen-bindings [TS_OUT_DIR] [SCHEMA_OUT_FILE]
//! Defaults: ui/src/generated and schema/4s.schema.json (relative to repo root).

use fours_protocol::*;
use std::path::PathBuf;
use ts_rs::TS;

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let mut args = std::env::args().skip(1);
    let ts_dir = args.next().map(PathBuf::from).unwrap_or_else(|| root.join("ui/src/generated"));
    let schema_file =
        args.next().map(PathBuf::from).unwrap_or_else(|| root.join("schema/4s.schema.json"));

    if ts_dir.exists() {
        std::fs::remove_dir_all(&ts_dir).expect("clear ts dir");
    }
    std::fs::create_dir_all(&ts_dir).expect("create ts dir");

    export_ts(&ts_dir).expect("export api types");
    let cfg = ts_rs::Config::default().with_out_dir(&ts_dir);
    EventEnvelope::export_all(&cfg).expect("export events");
    ProjectFile::export_all(&cfg).expect("export project");
    std::fs::write(ts_dir.join("methods.ts"), ts_method_map()).expect("write methods.ts");

    let mut index = String::from("// Generated by gen-bindings. Do not edit.\n");
    let mut names: Vec<_> = std::fs::read_dir(&ts_dir)
        .unwrap()
        .filter_map(|e| e.ok())
        .map(|e| e.file_name().to_string_lossy().to_string())
        .filter(|n| n.ends_with(".ts") && n != "index.ts")
        .collect();
    names.sort();
    for n in names {
        index.push_str(&format!("export * from \"./{}\";\n", n.trim_end_matches(".ts")));
    }
    std::fs::write(ts_dir.join("index.ts"), index).expect("write index.ts");

    let schema = serde_json::json!({
        "$comment": "Generated by gen-bindings from crates/protocol. Do not edit.",
        "protocol_version": PROTOCOL_VERSION,
        "project_format_version": PROJECT_FORMAT_VERSION,
        "request": schemars::schema_for!(Request),
        "event": schemars::schema_for!(EventEnvelope),
        "snapshot": schemars::schema_for!(Snapshot),
        "project": schemars::schema_for!(ProjectFile),
    });
    if let Some(parent) = schema_file.parent() {
        std::fs::create_dir_all(parent).expect("create schema dir");
    }
    let mut s = serde_json::to_string_pretty(&schema).unwrap();
    s.push('\n');
    std::fs::write(&schema_file, s).expect("write schema");

    println!("wrote {} and {}", ts_dir.display(), schema_file.display());
}
